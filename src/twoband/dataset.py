"""Generate probe, pump and pump-probe traces with the two-band simulator.

The files use the same column layout as the notebooks expect:
0 = time (a.u.), 1 = A(t), 4 = J(t), 7 = E(t). The other columns are zero.
A delay scan is written as consecutive blocks, one block of ``n_t`` rows per delay,
each block starting at time 0.
"""

import argparse
import json
from dataclasses import asdict, dataclass, field
from pathlib import Path

import numpy as np

from twoband.constants import AU_TO_FS, HARTREE_TO_EV
from twoband.pulses import (
    field_from_vector_potential,
    intensity_to_field,
    sin4_field,
    vector_potential,
)
from twoband.simulate import TwoBandModel, propagate

N_COLUMNS = 8
COL_TIME, COL_A, COL_J, COL_E = 0, 1, 4, 7

FILES = {
    "probe": "probe.out",
    "pump": "pump.out",
    "pump_probe": "pump_probe.out",
    "delay_scan": "delay_scan.out",
}


@dataclass
class DatasetConfig:
    """Everything needed to reproduce a generated dataset (atomic units unless noted)."""

    e_gap_ev: float = 4.45
    m_c: float = 0.3
    m_v: float = 0.5
    p_vc: float = 0.96
    k_max: float = 0.6
    n_k: int = 2401
    dt: float = 0.05
    t_end: float = 1600.0
    pump_intensity_w_cm2: float = 5e11
    pump_photon_ev: float = 1.55
    pump_duration_fs: float = 20.0
    probe_intensity_w_cm2: float = 3e8
    probe_photon_ev: float = 10.0
    probe_duration_fs: float = 1.0
    pump_center_fs: float = 14.5
    single_delay_fs: float = 0.0
    delays_fs: list = field(default_factory=lambda: list(np.linspace(-1.33, 1.33, 12)))

    def model(self) -> TwoBandModel:
        return TwoBandModel(
            e_gap=self.e_gap_ev / HARTREE_TO_EV,
            m_c=self.m_c,
            m_v=self.m_v,
            p_vc=self.p_vc,
            k_max=self.k_max,
            n_k=self.n_k,
        )

    def time(self) -> np.ndarray:
        return np.arange(0.0, self.t_end + 0.5 * self.dt, self.dt)

    def pump_field(self, time):
        return sin4_field(
            time,
            intensity_to_field(self.pump_intensity_w_cm2),
            self.pump_photon_ev / HARTREE_TO_EV,
            self.pump_duration_fs / AU_TO_FS,
            self.pump_center_fs / AU_TO_FS,
        )

    def probe_field(self, time, delay_fs):
        return sin4_field(
            time,
            intensity_to_field(self.probe_intensity_w_cm2),
            self.probe_photon_ev / HARTREE_TO_EV,
            self.probe_duration_fs / AU_TO_FS,
            (self.pump_center_fs + delay_fs) / AU_TO_FS,
        )


def _trace(time, a, j):
    data = np.zeros((time.size, N_COLUMNS))
    data[:, COL_TIME] = time
    data[:, COL_A] = a
    data[:, COL_J] = j
    data[:, COL_E] = field_from_vector_potential(time, a)
    return data


def generate_dataset(out_dir, config: DatasetConfig | None = None, verbose: bool = True) -> dict:
    """Run all simulations and write the trace files plus ``metadata.json`` to ``out_dir``."""
    config = config or DatasetConfig()
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    model = config.model()
    time = config.time()

    def log(message):
        if verbose:
            print(message, flush=True)

    a_pump = vector_potential(time, config.pump_field(time))
    a_probe = vector_potential(time, config.probe_field(time, config.single_delay_fs))

    a_scan = np.vstack(
        [a_pump + vector_potential(time, config.probe_field(time, d)) for d in config.delays_fs]
    )
    n_delays = len(config.delays_fs)
    log(f"propagating probe, pump, pump-probe and {n_delays} delays in one pass ...")
    runs = propagate(model, time, np.vstack([a_probe, a_pump, a_pump + a_probe, a_scan]))
    np.savetxt(out_dir / FILES["probe"], _trace(time, a_probe, runs[0]))
    np.savetxt(out_dir / FILES["pump"], _trace(time, a_pump, runs[1]))
    np.savetxt(out_dir / FILES["pump_probe"], _trace(time, a_pump + a_probe, runs[2]))
    blocks = [_trace(time, a_scan[i], runs[3 + i]) for i in range(n_delays)]
    np.savetxt(out_dir / FILES["delay_scan"], np.vstack(blocks))

    metadata = {
        "generator": "twoband.dataset",
        "description": (
            "Generated by the twoband 1D parabolic two-band simulator, not measured data."
        ),
        "files": FILES,
        "columns": {"time": COL_TIME, "vector_potential": COL_A, "current": COL_J, "field": COL_E},
        "block_length": int(time.size),
        "config": {
            k: (list(map(float, v)) if isinstance(v, list) else v)
            for k, v in asdict(config).items()
        },
    }
    (out_dir / "metadata.json").write_text(json.dumps(metadata, indent=2))
    log(f"done, files written to {out_dir}")
    return metadata


def load_or_generate(data_dir, config: DatasetConfig | None = None) -> dict:
    """Return the metadata of the dataset in ``data_dir``, generating it first if needed."""
    data_dir = Path(data_dir)
    meta_path = data_dir / "metadata.json"
    complete = meta_path.exists() and all((data_dir / f).exists() for f in FILES.values())
    if not complete:
        print(f"No generated data in {data_dir}, running the simulator (about 2 minutes) ...")
        return generate_dataset(data_dir, config)
    return json.loads(meta_path.read_text())


def main(argv=None):
    parser = argparse.ArgumentParser(
        description="Generate two-band model traces for the notebooks."
    )
    parser.add_argument("--out", default="data", help="output folder (default: data)")
    parser.add_argument("--n-delays", type=int, default=12, help="number of pump-probe delays")
    args = parser.parse_args(argv)
    config = DatasetConfig(delays_fs=list(np.linspace(-1.33, 1.33, args.n_delays)))
    generate_dataset(args.out, config)


if __name__ == "__main__":
    main()
